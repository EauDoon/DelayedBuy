"""Build the visual report's offline display rows from the model's checked CSV."""
import csv
from decimal import Decimal as D, ROUND_HALF_UP
from pathlib import Path
import json
ROOT = Path(__file__).resolve().parents[1]

def render():
    rows = []
    with (ROOT / 'economics/sensitivity.csv').open(newline='') as src:
        for r in csv.DictReader(src):
            rows.append([int(r['principal']), int(r['days']), int(D(r['apr']) * 100),
                         *[format(D(r[k]).quantize(D(q), rounding=ROUND_HALF_UP), 'f') for k,q in
                           [('gross_interest','.0001'),('cancel_shopper','.01'),('cancel_merchant','.01'),('incremental_result','.0001')]]])
    assert len({tuple(row[:3]) for row in rows}) == len(rows) == 64
    source = (ROOT / 'economics/sensitivity.csv').read_text(encoding='utf-8')
    columns = ('principal', 'apr', 'complete_days', 'cancel_days', 'cancel_rate',
               'avg_merchant_yield', 'card', 'refund', 'conversion', 'disputes',
               'gas', 'ops', 'total_cost', 'control_cost', 'incremental_result')
    labels = ('base cohort', 'existing funded stablecoin wallets')
    with (ROOT / 'economics/scenarios.csv').open(newline='') as src:
        cases = {r['scenario']: {k: r[k] for k in columns} for r in csv.DictReader(src)
                 if r['scenario'] in labels}
    fixed = [cases[label] for label in labels]
    values = {'reportRows': rows, 'fundingComparison': fixed, 'sensitivityCsv': source}
    return ('// Generated by scripts/build_report_data.py; rows are display values, not financial quotes.\n'
            + ''.join('export function ' + name + '() { return '
                      + json.dumps(value, separators=(',', ':')) + '; }\n'
                      for name, value in values.items()))

if __name__ == '__main__':
    (ROOT / 'ui/report-data.mjs').write_text(render(), encoding='utf-8')
